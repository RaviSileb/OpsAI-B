_PG_SCHEMA = """
CREATE TABLE IF NOT EXISTS {table} (
    rid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts TIMESTAMPTZ NOT NULL,
    ts_raw TEXT NOT NULL DEFAULT '',
    ts_quality INTEGER NOT NULL DEFAULT 0,
    ingest_ts TIMESTAMPTZ NOT NULL,
    source_type TEXT NOT NULL DEFAULT 'file',
    origin_host TEXT,
    origin_host_rule TEXT,
    service TEXT,
    level INTEGER,
    level_raw TEXT,
    message TEXT NOT NULL,
    message_lc TEXT NOT NULL,
    raw TEXT,
    fields JSONB NOT NULL DEFAULT '{}',
    src_meta JSONB NOT NULL DEFAULT '{}',
    template_id INTEGER
);
"""


def _render(template: str, **parts: str) -> str:
    """Substitute validated fragments into a constant SQL template."""
    out = template
    for key, value in parts.items():
        out = out.replace("{" + key + "}", value)
    return out


def _validate_session_id(session_id: str) -> str:
    if not SESSION_ID_RE.fullmatch(session_id):
        msg = f"Invalid session id {session_id!r}"
        raise ValueError(msg)
    return session_id


def _regexp(pattern: str, value: Any) -> int:
    if value is None:
        return 0
    try:
        return 1 if re.search(pattern, str(value)) else 0
    except re.error:
        return 0


def _wrap_query_error(exc: Exception, backend: str) -> OQLSyntaxError:
    # User-supplied OQL (notably regex) can fail at runtime on engines
    # whose regex flavor differs from Python `re`; report it as a 400.
    msg = f"Query failed on {backend} backend: {exc}"
    raise OQLSyntaxError(msg) from exc


class SessionBackend(ABC):
    """Record store for one backend engine."""

    name: str = "base"
    dialect: str = "sqlite"

    @abstractmethod
    def create_store(self, session_id: str) -> None:
        """Create an empty record store."""

    @abstractmethod
    def delete_store(self, session_id: str) -> None:
        """Drop the record store."""

    @abstractmethod
    def store_exists(self, session_id: str) -> bool:
        """Return True when the record store exists."""

    @abstractmethod
    def insert(self, session_id: str, rows: list[tuple[Any, ...]]) -> None:
        """Append rows in _INSERT_COLUMNS order."""

    @abstractmethod
    def count(self, session_id: str, where: str, params: list[Any], cursor: int) -> int:
        """Count records past the cursor matching the OQL fragment."""

    @abstractmethod
    def select(
        self, session_id: str, where: str, params: list[Any], cursor: int, limit: int
    ) -> list[tuple[Any, ...]]:
        """Return (rid, ts, source, host, service, level, message) rows."""

    @abstractmethod
    def get(self, session_id: str, rid: int) -> tuple[Any, ...] | None:
        """Return one full row (14 columns, ts ISO, fields/src_meta JSON)."""

    @abstractmethod
    def stats(
        self, session_id: str, where: str, params: list[Any]
    ) -> tuple[int, list[tuple[Any, ...]], list[tuple[Any, ...]], list[tuple[Any, ...]]]:
        """Return (total, by_level, by_host, by_service) row lists."""


class SQLiteBackend(SessionBackend):
    """One SQLite file per session (legacy default, always available)."""

    name = "sqlite"
    dialect = "sqlite"

    def __init__(self, sessions_dir: Path) -> None:
        self.sessions_dir = sessions_dir

    def _path(self, session_id: str) -> Path:
        return self.sessions_dir / f"{_validate_session_id(session_id)}.sqlite"

    def _connect(self, session_id: str) -> sqlite3.Connection:
        conn = sqlite3.connect(self._path(session_id))
        conn.create_function("REGEXP", 2, _regexp)
        return conn

    def create_store(self, session_id: str) -> None:
        with self._connect(session_id) as conn:
            conn.executescript(_SQLITE_SCHEMA)
            conn.commit()

    def delete_store(self, session_id: str) -> None:
        self._path(session_id).unlink(missing_ok=True)

    def store_exists(self, session_id: str) -> bool:
        return self._path(session_id).exists()

    def insert(self, session_id: str, rows: list[tuple[Any, ...]]) -> None:
        if not rows:
            return
        sql = _render(
            "INSERT INTO records ({_cols}) VALUES ({_marks})",
            _cols=_INSERT_COLUMNS,
            _marks=_INSERT_MARKS_Q,
        )
        with self._connect(session_id) as conn:
            conn.executemany(sql, rows)
            conn.commit()

    def count(self, session_id: str, where: str, params: list[Any], cursor: int) -> int:
        with self._connect(session_id) as conn:
            row = conn.execute(_render(_COUNT_SQL, where=where), [cursor, *params]).fetchone()
        return int(row[0])

    def select(
        self, session_id: str, where: str, params: list[Any], cursor: int, limit: int
    ) -> list[tuple[Any, ...]]:
        with self._connect(session_id) as conn:
            rows = conn.execute(
                _render(_SELECT_SQL, where=where), [cursor, *params, limit]
            ).fetchall()
        return [tuple(row) for row in rows]

    def get(self, session_id: str, rid: int) -> tuple[Any, ...] | None:
        with self._connect(session_id) as conn:
            row = conn.execute(_GET_SQL, (rid,)).fetchone()
        return tuple(row) if row is not None else None

    def stats(
        self, session_id: str, where: str, params: list[Any]
    ) -> tuple[int, list[tuple[Any, ...]], list[tuple[Any, ...]], list[tuple[Any, ...]]]:
        with self._connect(session_id) as conn:
            total = conn.execute(_render(_STATS_TOTAL_SQL, where=where), params).fetchone()[0]
            by_level = conn.execute(_render(_STATS_LEVEL_SQL, where=where), params).fetchall()
            by_host = conn.execute(_render(_STATS_HOST_SQL, where=where), params).fetchall()
            by_service = conn.execute(_render(_STATS_SERVICE_SQL, where=where), params).fetchall()
        return (
            int(total),
            [tuple(r) for r in by_level],
            [tuple(r) for r in by_host],
            [tuple(r) for r in by_service],
        )


class DuckDBBackend(SessionBackend):
    """One DuckDB file per session (desktop default, FR-140)."""

    name = "duckdb"
    dialect = "duckdb"

    def __init__(self, sessions_dir: Path) -> None:
        self.sessions_dir = sessions_dir
        self._locks: dict[str, threading.Lock] = {}
        self._locks_guard = threading.Lock()

    def _path(self, session_id: str) -> Path:
        return self.sessions_dir / f"{_validate_session_id(session_id)}.duckdb"

    def _lock_for(self, session_id: str) -> threading.Lock:
        with self._locks_guard:
            lock = self._locks.get(session_id)
            if lock is None:
                lock = threading.Lock()
                self._locks[session_id] = lock
            return lock

    def _connect(self, session_id: str) -> Any:
        import duckdb

        conn = duckdb.connect(str(self._path(session_id)))
        conn.execute("PRAGMA memory_limit='2GB'")
        return conn

    def create_store(self, session_id: str) -> None:
        conn = self._connect(session_id)
        try:
            conn.execute(_DUCKDB_SCHEMA)
        finally:
            conn.close()

    def delete_store(self, session_id: str) -> None:
        with self._locks_guard:
            self._locks.pop(session_id, None)
        self._path(session_id).unlink(missing_ok=True)
        wal = self._path(session_id).with_suffix(".duckdb.wal")
        wal.unlink(missing_ok=True)

    def store_exists(self, session_id: str) -> bool:
        return self._path(session_id).exists()

    def insert(self, session_id: str, rows: list[tuple[Any, ...]]) -> None:
        if not rows:
            return
        sql = _render(
            "INSERT INTO records ({_cols}) VALUES ({_marks})",
            _cols=_INSERT_COLUMNS,
            _marks=_INSERT_MARKS_Q,
        )
        # DuckDB serializes writers; front them with a per-session lock.
        with self._lock_for(session_id):
            conn = self._connect(session_id)
            try:
                conn.executemany(sql, rows)
            finally:
                conn.close()

    def count(self, session_id: str, where: str, params: list[Any], cursor: int) -> int:
        conn = self._connect(session_id)
        try:
            row = conn.execute(_render(_COUNT_SQL, where=where), [cursor, *params]).fetchone()
        except Exception as exc:
            raise _wrap_query_error(exc, self.name) from exc
        finally:
            conn.close()
        return int(row[0])

    def select(
        self, session_id: str, where: str, params: list[Any], cursor: int, limit: int
    ) -> list[tuple[Any, ...]]:
        conn = self._connect(session_id)
        try:
            rows = conn.execute(
                _render(_SELECT_SQL, where=where), [cursor, *params, limit]
            ).fetchall()
        except Exception as exc:
            raise _wrap_query_error(exc, self.name) from exc
        finally:
            conn.close()
        return [tuple(row) for row in rows]

    def get(self, session_id: str, rid: int) -> tuple[Any, ...] | None:
        conn = self._connect(session_id)
        try:
            row = conn.execute(_GET_SQL, [rid]).fetchone()
        finally:
            conn.close()
        return tuple(row) if row is not None else None

    def stats(
        self, session_id: str, where: str, params: list[Any]
    ) -> tuple[int, list[tuple[Any, ...]], list[tuple[Any, ...]], list[tuple[Any, ...]]]:
        conn = self._connect(session_id)
        try:
            total = conn.execute(_render(_STATS_TOTAL_SQL, where=where), params).fetchone()[0]
            by_level = conn.execute(_render(_STATS_LEVEL_SQL, where=where), params).fetchall()
            by_host = conn.execute(_render(_STATS_HOST_SQL, where=where), params).fetchall()
            by_service = conn.execute(_render(_STATS_SERVICE_SQL, where=where), params).fetchall()
        except Exception as exc:
            raise _wrap_query_error(exc, self.name) from exc
        finally:
            conn.close()
        return (
            int(total),
            [tuple(r) for r in by_level],
            [tuple(r) for r in by_host],
            [tuple(r) for r in by_service],
        )


class PostgresBackend(SessionBackend):
    """One table per session in PostgreSQL (server form, FR-140)."""

    name = "postgres"
    dialect = "postgres"

    def __init__(self, dsn: str) -> None:
        if not dsn:
            msg = "PostgreSQL backend requires a DSN (OPSAI_POSTGRES_DSN)"
            raise ValueError(msg)
        self.dsn = dsn

    def _table(self, session_id: str) -> str:
        # Hex-only ids make the table name safe to interpolate.
        return f"session_records_{_validate_session_id(session_id)}"

    def _connect(self) -> Any:
        import psycopg

        return psycopg.connect(self.dsn, autocommit=True)

    def create_store(self, session_id: str) -> None:
        table = self._table(session_id)
        with self._connect() as conn, conn.cursor() as cur:
            try:
                cur.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm")
            except Exception as exc:
                msg = f"PostgreSQL backend needs the pg_trgm extension: {exc}"
                raise RuntimeError(msg) from exc
            cur.execute(_render(_PG_SCHEMA, table=table))
            cur.execute(
                _render(
                    "CREATE INDEX IF NOT EXISTS {table}_ts ON {table} USING BRIN (ts)",
                    table=table,
                )
            )
            cur.execute(
                _render(
                    "CREATE INDEX IF NOT EXISTS {table}_msg ON {table}"
                    " USING GIN (message_lc gin_trgm_ops)",
                    table=table,
                )
            )
            cur.execute(
                _render(
                    "CREATE INDEX IF NOT EXISTS {table}_lvl ON {table} (level)",
                    table=table,
                )
            )
            cur.execute(
                _render(
                    "CREATE INDEX IF NOT EXISTS {table}_host ON {table} (origin_host)",
                    table=table,
                )
            )

    def delete_store(self, session_id: str) -> None:
        with self._connect() as conn, conn.cursor() as cur:
            cur.execute(_render("DROP TABLE IF EXISTS {table}", table=self._table(session_id)))

    def store_exists(self, session_id: str) -> bool:
        with self._connect() as conn, conn.cursor() as cur:
            cur.execute("SELECT to_regclass(%s)", (self._table(session_id),))
            row = cur.fetchone()
        return row is not None and row[0] is not None

    def insert(self, session_id: str, rows: list[tuple[Any, ...]]) -> None:
        if not rows:
            return
        sql = _render(
            "INSERT INTO {table} ({_cols}) VALUES ({_marks})",
            table=self._table(session_id),
            _cols=_INSERT_COLUMNS,
            _marks=_INSERT_MARKS_P,
        )
        with self._connect() as conn, conn.cursor() as cur:
            cur.executemany(sql, rows)

    def count(self, session_id: str, where: str, params: list[Any], cursor: int) -> int:
        table = self._table(session_id)
        try:
            with self._connect() as conn, conn.cursor() as cur:
                cur.execute(_render(_PG_COUNT_SQL, table=table, where=where), [cursor, *params])
                row = cur.fetchone()
        except Exception as exc:
            raise _wrap_query_error(exc, self.name) from exc
        assert row is not None
        return int(row[0])

    def select(
        self, session_id: str, where: str, params: list[Any], cursor: int, limit: int
    ) -> list[tuple[Any, ...]]:
        table = self._table(session_id)
        try:
            with self._connect() as conn, conn.cursor() as cur:
                cur.execute(
                    _render(_PG_SELECT_SQL, table=table, where=where),
                    [cursor, *params, limit],
                )
                rows = cur.fetchall()
        except Exception as exc:
            raise _wrap_query_error(exc, self.name) from exc
        return [
            (
                row[0],
                row[1].isoformat() if row[1] is not None else None,
                row[2],
                row[3],
                row[4],
                row[5],
                row[6],
            )
            for row in rows
        ]

    def get(self, session_id: str, rid: int) -> tuple[Any, ...] | None:
        table = self._table(session_id)
        with self._connect() as conn, conn.cursor() as cur:
            cur.execute(_render(_PG_GET_SQL, table=table), (rid,))
            row = cur.fetchone()
        if row is None:
            return None
        ts = row[1].isoformat() if row[1] is not None else None
        fields = row[11] if isinstance(row[11], str) else json.dumps(row[11])
        src_meta = row[12] if isinstance(row[12], str) else json.dumps(row[12])
        return (
            row[0],
            ts,
            row[2],
            row[3],
            row[4],
            row[5],
            row[6],
            row[7],
            row[8],
            row[9],
            row[10],
            fields,
            src_meta,
            row[13],
        )

    def stats(
        self, session_id: str, where: str, params: list[Any]
    ) -> tuple[int, list[tuple[Any, ...]], list[tuple[Any, ...]], list[tuple[Any, ...]]]:
        table = self._table(session_id)
        try:
            with self._connect() as conn, conn.cursor() as cur:
                cur.execute(_render(_PG_STATS_TOTAL_SQL, table=table, where=where), params)
                total_row = cur.fetchone()
                cur.execute(_render(_PG_STATS_LEVEL_SQL, table=table, where=where), params)
                by_level = cur.fetchall()
                cur.execute(_render(_PG_STATS_HOST_SQL, table=table, where=where), params)
                by_host = cur.fetchall()
                cur.execute(_render(_PG_STATS_SERVICE_SQL, table=table, where=where), params)
                by_service = cur.fetchall()
        except Exception as exc:
            raise _wrap_query_error(exc, self.name) from exc
        assert total_row is not None
        return (
            int(total_row[0]),
            [tuple(r) for r in by_level],
            [tuple(r) for r in by_host],
            [tuple(r) for r in by_service],
        )
