"""Session record-store backends: SQLite, DuckDB, PostgreSQL (TZ FR-140).

All backends expose one interface; :class:`SessionManager` keeps the
metadata in app.db and routes each session to its stored backend.
Row tuples use a fixed column order shared by every backend.

SQL is built from constant templates plus :func:`_render` substitution
(the project-wide B608-safe pattern): WHERE fragments come from the OQL
compiler (whitelisted identifiers, bound values) and table names embed
hex-only session ids validated by :func:`_validate_session_id`.
"""

from __future__ import annotations

import json
import re
import sqlite3
import threading
from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any

from opsai.core.query import OQLSyntaxError

SESSION_ID_RE = re.compile(r"[0-9a-f]{32}")

_INSERT_COLUMNS = (
    "ts, ts_raw, ts_quality, ingest_ts, source_type, origin_host,"
    " origin_host_rule, service, level, level_raw, message, message_lc,"
    " raw, fields, src_meta, template_id"
)
_INSERT_MARKS_Q = ", ".join(["?"] * 16)
_INSERT_MARKS_P = ", ".join(["%s"] * 16)

_COUNT_SQL = "SELECT COUNT(*) FROM records WHERE rid > ? AND ({where})"
_SELECT_SQL = (
    "SELECT rid, ts, source_type, origin_host, service, level, message"
    " FROM records WHERE rid > ? AND ({where}) ORDER BY rid ASC LIMIT ?"
)
_GET_SQL = (
    "SELECT rid, ts, ts_raw, source_type, origin_host, origin_host_rule,"
    " service, level, level_raw, message, raw, fields, src_meta, template_id"
    " FROM records WHERE rid = ?"
)
_STATS_TOTAL_SQL = "SELECT COUNT(*) FROM records WHERE {where}"
_STATS_LEVEL_SQL = "SELECT level, COUNT(*) FROM records WHERE {where} GROUP BY level"
_STATS_HOST_SQL = (
    "SELECT COALESCE(origin_host, ''), COUNT(*) FROM records WHERE {where}"
    " GROUP BY origin_host ORDER BY COUNT(*) DESC LIMIT 20"
)
_STATS_SERVICE_SQL = (
    "SELECT COALESCE(service, ''), COUNT(*) FROM records WHERE {where}"
    " GROUP BY service ORDER BY COUNT(*) DESC LIMIT 20"
)

_PG_COUNT_SQL = "SELECT COUNT(*) FROM {table} WHERE rid > %s AND ({where})"
_PG_SELECT_SQL = (
    "SELECT rid, ts, source_type, origin_host, service, level, message"
    " FROM {table} WHERE rid > %s AND ({where}) ORDER BY rid ASC LIMIT %s"
)
_PG_GET_SQL = (
    "SELECT rid, ts, ts_raw, source_type, origin_host, origin_host_rule,"
    " service, level, level_raw, message, raw, fields, src_meta, template_id"
    " FROM {table} WHERE rid = %s"
)
_PG_STATS_TOTAL_SQL = "SELECT COUNT(*) FROM {table} WHERE {where}"
_PG_STATS_LEVEL_SQL = "SELECT level, COUNT(*) FROM {table} WHERE {where} GROUP BY level"
_PG_STATS_HOST_SQL = (
    "SELECT COALESCE(origin_host, ''), COUNT(*) FROM {table} WHERE {where}"
    " GROUP BY origin_host ORDER BY COUNT(*) DESC LIMIT 20"
)
_PG_STATS_SERVICE_SQL = (
    "SELECT COALESCE(service, ''), COUNT(*) FROM {table} WHERE {where}"
    " GROUP BY service ORDER BY COUNT(*) DESC LIMIT 20"
)

